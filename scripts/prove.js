// Generates docs/evidence/generated-episode-proof.md from REAL runs: nothing in the report is typed by hand
// except the "skipped" section. Run after committing so the commit hash is the code that produced it.
import { spawnSync } from 'node:child_process';
import { copyFileSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createClient } from '../src/model/adapter.js';
import { runPipeline, renderEvent, writeOutputs } from '../src/pipeline.js';
import { loadBrief, makeReview } from '../src/cli.js';
import { verifyEpisodeFile } from '../src/verify.js';
import { line13Root } from '../src/lib/line13.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const git = (...a) => spawnSync('git', a, { cwd: ROOT, encoding: 'utf8' }).stdout.trim();
const commit = git('rev-parse', 'HEAD');
const dirty = git('status', '--porcelain', '--', 'src', 'test', 'fixtures', '.kiro', 'contracts', 'scripts');

async function execute(briefId, reviewer) {
  const brief = loadBrief(briefId);
  const client = createClient({ fixturesDir: path.join(ROOT, 'fixtures/dry-run'), briefId: brief.briefId, fallbackBriefId: brief.fixturesFrom });
  const lines = [];
  let review;
  const result = await runPipeline({
    brief, client, onEvent: (e) => lines.push(renderEvent(e)),
    review: reviewer ? (m) => (review = makeReview(m, reviewer)) : null,
  });
  return { brief, client, result, lines, review };
}

const main = await execute('first-night', 'S Logesh');
const outDir = path.join(ROOT, 'out', main.brief.episodeId);
rmSync(outDir, { recursive: true, force: true });
writeOutputs(outDir, main.result, main.brief, { review: main.review });
const episodePath = path.join(outDir, 'episode.json');
const verification = await verifyEpisodeFile(episodePath);

const evidenceDir = path.join(ROOT, 'docs/evidence');
mkdirSync(evidenceDir, { recursive: true });
copyFileSync(episodePath, path.join(evidenceDir, 'the-drowned-shift.episode.json'));
copyFileSync(path.join(outDir, 'review.json'), path.join(evidenceDir, 'the-drowned-shift.review.json'));
copyFileSync(path.join(outDir, 'transcript.txt'), path.join(evidenceDir, 'the-drowned-shift.transcript.txt'));

const nearby = [];
for (const id of ['short-shift', 'stubborn']) {
  const r = await execute(id, 'S Logesh');
  nearby.push({ id, status: r.result.status, reason: r.result.reason ?? '', rewinds: r.result.events.filter((e) => e.type === 'rewind').length, solutions: r.result.report?.solutionCount ?? 'n/a', aws: r.client.awsCalls });
}

const tests = spawnSync(process.execPath, ['--test', ...readdirSync(path.join(ROOT, 'test')).filter((f) => f.endsWith('.test.js')).map((f) => `test/${f}`)], { cwd: ROOT, encoding: 'utf8' });
const pick = (k) => (new RegExp(`^# ${k} (\\d+)`, 'm').exec(tests.stdout) ?? [])[1];
const totals = `tests ${pick('tests')}, suites ${pick('suites')}, pass ${pick('pass')}, fail ${pick('fail')}, skipped ${pick('skipped')}`;
const l13 = git('-C', line13Root(), 'rev-parse', '--short', 'HEAD');
const manifest = JSON.parse(readFileSync(episodePath, 'utf8'));
const s = verification.solver;
const solution = manifest.intendedRoutes.map((r) => `${r.order}. ${r.callerId} -> ${r.destinationId}`).join('\n');
const ambiguous = main.lines.filter((l) => /solver: FAIL|AMBIGUOUS|REWIND|attempt 2|solver: PASS/.test(l)).slice(0, 5).join('\n');

const md = `# Night Operator: generated-episode proof

Author: S Logesh. Generated by \`node scripts/prove.js\` from real runs; nothing below is hand-typed except "What I skipped".

- Night Operator commit (code that produced this): \`${commit}\`${dirty ? '  (WARNING: uncommitted changes in code dirs)' : ''}
- LINE 13 checkout used (read-only): \`${line13Root()}\` @ \`${l13}\`
- Mode: dry-run (fixtures). Model calls: ${main.client.calls.length}. AWS calls: ${main.client.awsCalls}.
- Generated episode: \`out/${main.brief.episodeId}/episode.json\` (git-ignored working copy); committed copy: \`docs/evidence/the-drowned-shift.episode.json\`
- Human gate: reviewer record \`docs/evidence/the-drowned-shift.review.json\` was created with \`--approve-as "S Logesh"\`, i.e. the author's recorded approval of this dry-run output.

## 1. Pipeline transcript (first-night)

\`\`\`
${main.lines.join('\n')}
\`\`\`

## 2. Gate rejection of a deliberately ambiguous draft, and the retry fixing it

The Puzzle Architect's first draft (fixture \`puzzle-architect.1.json\`) leaves three callers free. Extract:

\`\`\`
${ambiguous}
\`\`\`

The retry (attempt 2) received that feedback in its prompt (asserted in \`test/pipeline.test.js\`) and added clue \`clue-tobias-quiet\`; the solver then reports exactly one solution.

## 3. LINE 13's own verification of the output (\`node src/cli.js verify\`, read-only imports of LINE 13 code)

- LINE 13 \`validateEpisodeManifest\` (packages/contracts): ok = ${verification.contract.ok}
- LINE 13 solver \`computeProofReport\` (packages/graph): status = ${s.status}, solutionCount = ${s.solutionCount}, truncated = ${s.solutionsTruncated}, shortestSolutionLength = ${s.shortestSolutionLength}, unreachableNodeIds = ${JSON.stringify(s.unreachableNodeIds)}, intendedSolutionMatches = ${s.intendedSolutionMatches}
- Recovery sweep: exhaustive = ${s.recoverability.exhaustive}, statesChecked = ${s.recoverability.statesChecked}, unrecoverable = ${s.recoverability.unrecoverableStateKeys.length}
- Difficulty: ${JSON.stringify(s.difficulty)}; proofHash \`${s.proofHash}\`; validator ${s.validatorVersion}
- LINE 13 \`verifyManifestIntegrity\` (apps/api): ok = ${verification.integrity.ok}, manifestHash \`${verification.integrity.manifestHash}\`
- LINE 13 \`evaluatePublicationGate\` (apps/api) with the review record: ok = ${verification.publicationGate?.ok}
- LINE 13 web \`adoptRemoteEpisode\` (apps/web): source = \`${verification.webImport.source}\`, notice = ${JSON.stringify(verification.webImport.notice)}, rejected issues = ${verification.webImport.rejectedIssues.length}
- Overall: **${verification.ok ? 'PASS, imports with no manual repair' : 'FAIL'}**

The single solution:

\`\`\`
${solution}
\`\`\`

## 4. Nearby inputs tested

| Input | Result |
|---|---|
| first-night (4 callers, 4 destinations, ambiguous first draft) | published after 1 rewind, 1 solution |
${nearby.map((n) => `| ${n.id} | status ${n.status}${n.reason ? ` (${n.reason})` : ''}, rewinds ${n.rewinds}, solutions ${n.solutions}, AWS calls ${n.aws} |`).join('\n')}
| contradictory constraints | solver gate rejects (NO_SOLUTION/EMPTY_DOMAIN) -> puzzle-architect |
| decoy destination nobody uses | rejected UNREACHABLE_NODES (LINE 13's publication gate blocks these) |
| intended order breaking an ordering clue | rejected ORDER_VIOLATED |
| clue not listed under any caller | rejected |
| missing reduced-motion / silent path / ring cue / reject cue / ending cue; flicker intensity 3 | accessibility gate -> stage-director |
| subtitle or clue above grade 8 | accessibility gate -> folklorist / puzzle-architect |
| third-party model name, gore, PII, minor in harm, self-harm | safety gate -> author of the text |
| unknown property, bad entity id, tampered hash, bad cue target, sound cue without asset, wrong proof hash, draft-status proof | schema gate |
| no review / blank reviewer / stale manifest hash / safety flag false | human gate holds, nothing published |
| model returns non-JSON | role retried 3x, then fail closed |
| ambiguous manifest fed straight to LINE 13 verify | LINE 13 itself reports 3 solutions, ok = false |
| live path with stub Bedrock transport (Nova Converse shape, fenced JSON) | full pipeline publishes; non-Nova ids refused |

## 5. Test totals

\`node --test test/*.test.js\`: ${totals} (exit ${tests.status})

## What I skipped

- No live Bedrock call was made (by instruction). The live path is implemented and exercised only with a stub transport; real Nova output quality, token limits and JSON adherence are unverified.
- Dry-run responses are authored fixtures, so "the model drafted this" is not demonstrated; what is demonstrated is the pipeline, gates, rework loop and LINE 13 acceptance.
- The human review in this proof is a recorded approval by flag, not an interactive review session.
- No audio assets or Polly voices (LINE 13 Milestone 5); the Stage Director avoids the sound channel.
- Not run inside the LINE 13 browser UI; import was checked through LINE 13's own web import function, not a Chromium session.
- Safety gate is lexical only; no semantic or Bedrock Guardrails screening.
- Observation about LINE 13, not changed: its publication gate blocks any episode whose solver proof lists an unreachable node, so decoy destinations cannot ship; the episode uses 4 callers and 4 destinations.
`;
writeFileSync(path.join(evidenceDir, 'generated-episode-proof.md'), md);
console.log(`wrote docs/evidence/generated-episode-proof.md (overall ${verification.ok ? 'PASS' : 'FAIL'}; ${totals})`);
process.exit(verification.ok && tests.status === 0 ? 0 : 1);
