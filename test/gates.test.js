import assert from 'node:assert/strict';
import { describe, it } from 'node:test';
import { goodDraft, reviewer } from './helpers.js';
import { solverGate } from '../src/gates/solver.js';
import { accessibilityGate } from '../src/gates/accessibility.js';
import { safetyGate } from '../src/gates/safety.js';
import { schemaGate } from '../src/gates/schema.js';
import { humanGate } from '../src/gates/human.js';
import { packageEpisode } from '../src/roles/packager.js';
import { sealManifest } from '../src/lib/canonical.js';

const codes = (g) => g.findings.map((f) => f.code);
const who = (g, code) => g.findings.find((f) => f.code === code)?.responsible;

describe('solver gate', () => {
  it('passes the good draft', async () => {
    const { draft, brief } = await goodDraft();
    assert.equal((await solverGate(draft, brief)).ok, true);
  });
  it('rejects a contradiction (no solution)', async () => {
    const { draft, brief } = await goodDraft();
    draft.puzzle.constraints.push({ kind: 'forbidden-route', callerId: 'caller-ruth', destinationId: 'destination-bell-tower' });
    const g = await solverGate(draft, brief);
    assert.equal(g.ok, false);
    assert.ok(codes(g).some((c) => ['NO_SOLUTION', 'EMPTY_DOMAIN'].includes(c)), codes(g).join());
    assert.equal(g.findings[0].responsible, 'puzzle-architect');
  });
  it('rejects a decoy destination that no solution uses', async () => {
    const { draft, brief } = await goodDraft();
    draft.story.destinations.push({ id: 'destination-attic', label: 'Attic', description: 'Dust and old wire.' });
    for (const c of draft.story.callers) draft.puzzle.constraints.push({ kind: 'forbidden-route', callerId: c.id, destinationId: 'destination-attic' });
    const g = await solverGate(draft, brief);
    assert.ok(codes(g).includes('UNREACHABLE_NODES'), codes(g).join());
  });
  it('rejects intended routes that break an ordering clue', async () => {
    const { draft, brief } = await goodDraft();
    const r = draft.puzzle.intendedRoutes;
    r.find((x) => x.callerId === 'caller-ines').order = 4;
    r.find((x) => x.callerId === 'caller-tobias').order = 3;
    assert.ok(codes(await solverGate(draft, brief)).includes('ORDER_VIOLATED'));
  });
  it('rejects a clue nobody owns', async () => {
    const { draft, brief } = await goodDraft();
    draft.puzzle.clueOwners['caller-tobias'] = ['clue-tobias-after-ines'];
    assert.equal((await solverGate(draft, brief)).ok, false);
  });
});

describe('accessibility gate', () => {
  it('passes the good draft', async () => {
    const { draft, brief } = await goodDraft();
    assert.deepEqual(accessibilityGate(draft, brief).findings, []);
  });
  it('flags motion with no reduced-motion alternative -> stage-director', async () => {
    const { draft, brief } = await goodDraft();
    draft.staging.cues.find((c) => c.channel === 'camera').reducedMotionAlternative = 'none';
    const g = accessibilityGate(draft, brief);
    assert.ok(codes(g).includes('NO_REDUCED_MOTION'));
    assert.equal(who(g, 'NO_REDUCED_MOTION'), 'stage-director');
  });
  it('flags a ring cue with no silent path', async () => {
    const { draft, brief } = await goodDraft();
    draft.staging.cues[0].silentAlternative = 'none';
    assert.ok(codes(accessibilityGate(draft, brief)).includes('NO_SILENT_PATH'));
  });
  it('flags a missing ring cue, reject cue and ending cue', async () => {
    const { draft, brief } = await goodDraft();
    draft.staging.cues = draft.staging.cues.filter((c) => c.id !== 'cue-ring-amos' && c.triggerEventType !== 'ROUTE_REJECTED' && c.id !== 'cue-end-answers');
    const g = accessibilityGate(draft, brief);
    for (const c of ['NO_RING_CUE', 'NO_REJECT_CUE', 'NO_ENDING_CUE']) assert.ok(codes(g).includes(c), c);
  });
  it('caps flicker intensity (photosensitivity)', async () => {
    const { draft, brief } = await goodDraft();
    draft.staging.cues.find((c) => c.effect === 'flicker').intensity = 3;
    assert.ok(codes(accessibilityGate(draft, brief)).includes('PHOTOSENSITIVITY'));
  });
  it('flags a subtitle above grade 8 -> folklorist, and a clue above grade 8 -> puzzle-architect', async () => {
    const { draft, brief } = await goodDraft();
    const hard = 'Notwithstanding unprecedented electromagnetic interference, interconnection necessitates immediate authorization.';
    draft.story.callers[0].subtitle = hard;
    draft.puzzle.clues[0].text = hard;
    const g = accessibilityGate(draft, brief);
    assert.deepEqual(g.findings.filter((f) => f.code === 'READING_LEVEL').map((f) => f.responsible).sort(), ['folklorist', 'puzzle-architect']);
  });
});

describe('safety gate', () => {
  it('passes the good draft', async () => {
    const { draft } = await goodDraft();
    assert.deepEqual(safetyGate(draft).findings, []);
  });
  for (const [code, text] of [
    ['THIRD_PARTY_MODEL', 'A voice generated by GPT-4 whispers.'],
    ['GRAPHIC_VIOLENCE', 'The line is full of gore and entrails.'],
    ['PII', 'Call me at 555-123-4567 or write to ruth@example.com.'],
    ['MINOR_IN_HARM', 'A child was murdered at the gate.'],
    ['SELF_HARM', 'He said he would kill himself.'],
  ]) {
    it(`blocks ${code} and routes it to the author of that text`, async () => {
      const { draft } = await goodDraft();
      draft.story.destinations[0].description = text;
      const g = safetyGate(draft);
      assert.ok(codes(g).includes(code), codes(g).join());
      assert.equal(who(g, code), 'folklorist');
    });
  }
  it('screens clue text and routes it to the Puzzle Architect', async () => {
    const { draft } = await goodDraft();
    draft.puzzle.clues[0].text = 'Ask Claude where the clock is.';
    assert.equal(who(safetyGate(draft), 'THIRD_PARTY_MODEL'), 'puzzle-architect');
  });
});

describe('schema gate', () => {
  const sealed = async () => {
    const { manifest } = await goodDraft();
    return manifest;
  };
  it('passes the sealed good manifest', async () => {
    assert.equal((await schemaGate(await sealed())).ok, true);
  });
  it('rejects an unknown property (contract is additionalProperties:false)', async () => {
    const m = await sealed();
    m.callers[0].backstory = 'leaked private note';
    const g = await schemaGate(sealManifest(m));
    assert.ok(codes(g).includes('SCHEMA'));
    assert.equal(who(g, 'SCHEMA'), 'folklorist');
  });
  it('rejects a bad entity id', async () => {
    const m = await sealed();
    m.destinations[0].id = 'Destination_Bell Tower';
    assert.ok(codes(await schemaGate(sealManifest(m))).includes('SCHEMA'));
  });
  it('rejects a tampered hash', async () => {
    const m = await sealed();
    m.title = 'Edited after sealing';
    assert.ok(codes(await schemaGate(m)).includes('INTEGRITY'));
  });
  it('rejects a lamp cue aimed at a line no caller owns, and a sound cue with no asset', async () => {
    const m = await sealed();
    m.cues[0].targetId = 'line-99';
    m.cues.push({ id: 'cue-sound', triggerEventType: 'CALL_RINGING', channel: 'sound', assetId: 'asset-x', effect: 'plain', intensity: 1, durationMs: 10, reducedMotionAlternative: 'none', silentAlternative: 'caption' });
    const g = await schemaGate(sealManifest(m));
    assert.ok(codes(g).includes('CUE_TARGET'));
    assert.ok(codes(g).includes('CUE_ASSET'));
  });
  it('rejects a proof that does not match a fresh solver run', async () => {
    const m = await sealed();
    m.solverProof.proofHash = '0000000000000000';
    assert.ok(codes(await schemaGate(sealManifest(m))).includes('PROOF_MISMATCH'));
  });
  it('rejects a draft-status proof', async () => {
    const { draft, brief } = await goodDraft();
    const g = await schemaGate(packageEpisode(draft, brief, null));
    assert.equal(g.ok, false);
  });
});

describe('human gate', () => {
  it('requires a named reviewer, safety flag, timestamp and the matching hash', async () => {
    const { manifest } = await goodDraft();
    assert.equal(humanGate(manifest, reviewer()(manifest)).ok, true);
    assert.ok(codes(humanGate(manifest, null)).includes('AWAITING_REVIEW'));
    assert.ok(codes(humanGate(manifest, { ...reviewer()(manifest), approvedBy: ' ' })).includes('NO_REVIEWER'));
    assert.ok(codes(humanGate(manifest, { ...reviewer()(manifest), safetyReviewPassed: false })).includes('SAFETY_REVIEW_MISSING'));
    assert.ok(codes(humanGate(manifest, { ...reviewer()(manifest), approvedAt: 'later' })).includes('NO_REVIEW_TIME'));
  });
});
